export function translateCatalogTag(tag: string, language: BotLanguage): string {
  const value = tag.trim();
  const translated = Object.hasOwn(translations, value) ? translations[value] : undefined;
  return translated && language !== 'en' ? translated[language === 'es' ? 0 : 1] : value;
}
